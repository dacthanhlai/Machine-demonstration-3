import React, { useState } from 'react';
import { MachineComponent, SuctionSystemConfig, MaterialFeedConfig, ClearanceItem, TechnicalConflict } from '../types/machine';
import { useLanguage } from '../i18n/LanguageContext';
import { getLocalizedComponentName } from '../utils/presets';
import { X, Copy, Check, Download, FileText, CheckCircle2 } from 'lucide-react';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  components: MachineComponent[];
  suctionConfig: SuctionSystemConfig;
  materialConfig: MaterialFeedConfig;
  clearances: ClearanceItem[];
  conflicts: TechnicalConflict[];
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  components,
  suctionConfig,
  materialConfig,
  clearances,
  conflicts,
}) => {
  const { language, t } = useLanguage();
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState<'json' | 'report'>('report');

  if (!isOpen) return null;

  const isEn = language === 'en';

  const localizedComponents = components.map((c) => ({
    ...c,
    name: getLocalizedComponentName(c.name, language),
  }));

  const exportData = {
    exportedAt: new Date().toISOString(),
    language,
    machineSummary: {
      totalComponents: components.length,
      material: materialConfig.materialName,
      feedRateKgH: materialConfig.feedRateKgPerHour,
      suctionVelocityMs: suctionConfig.airVelocity,
      safetyStatus: conflicts.length === 0 ? (isEn ? 'OPTIMAL' : 'AN TOÀN') : `${conflicts.length} ${isEn ? 'ISSUES DETECTED' : 'VẤN ĐỀ CẦN LƯU Ý'}`,
    },
    components: localizedComponents,
    suctionConfig,
    materialConfig,
    clearances,
  };

  const jsonString = JSON.stringify(exportData, null, 2);

  // Báo cáo kỹ thuật bằng văn bản tiếng Việt / tiếng Anh
  const technicalReport = isEn
    ? `=====================================================
TEXTEAR 3D - INDUSTRIAL TEXTILE TEARING MACHINE TECHNICAL REPORT
Export Timestamp: ${new Date().toLocaleString('en-US')}
=====================================================

1. OPERATIONAL & MATERIAL SPECIFICATIONS:
- Material Type: ${materialConfig.materialName}
- Feed Direction: ${materialConfig.feedDirection === 'left_to_right' ? 'Left to Right' : 'Right to Left'}
- Feed Speed: ${materialConfig.feedSpeedMPerMin} m/min (Output Capacity: ${materialConfig.feedRateKgPerHour} kg/h)
- Nominal Intake Tension: ${materialConfig.nominalTensionN} N
- Exhaust Suction System: ${suctionConfig.active ? 'ONLINE' : 'OFFLINE'} | Air Velocity: ${suctionConfig.airVelocity} m/s | Airflow Rate: ${suctionConfig.airflowRate} m³/h

2. MACHINE COMPONENTS & CYLINDERS (${components.length} components):
${components
  .map(
    (c, i) =>
      ` ${i + 1}. ${getLocalizedComponentName(c.name, 'en')} [${c.type}]
    - Center Coordinates: X=${c.x} mm, Y=${c.y} mm
    - Diameter Ø: ${c.diameter} mm | Length: ${c.length} mm
    - Rotation: ${c.rotationDir} | Speed: ${c.rpm} RPM
    - Surface: ${c.surfaceType}`
  )
  .join('\n')}

3. INTER-ROLLER GAP CLEARANCES (CLEARANCE MATRIX):
${clearances
  .map(
    (cl) =>
      `- ${getLocalizedComponentName(cl.nameA, 'en')} ↔ ${getLocalizedComponentName(cl.nameB, 'en')}: ${cl.gapMm} mm [Standard: ${cl.recommendedGapMin}-${cl.recommendedGapMax}mm] -> ${
        cl.gapMm < 0 ? 'CRITICAL COLLISION' : cl.status === 'optimal' ? 'OPTIMAL' : 'NEEDS ADJUSTMENT'
      }`
  )
  .join('\n')}

4. DIAGNOSTIC SAFETY ASSESSMENT (${conflicts.length} notices):
${
  conflicts.length === 0
    ? ' [✓] MACHINE CONFIGURATION IS 100% OPTIMAL. No mechanical collisions or rotation conflicts detected.'
    : conflicts
        .map(
          (cf, i) =>
            ` [!] ISSUE #${i + 1} (${cf.level.toUpperCase()}): ${cf.title}
     - Detail: ${cf.description}
     - Recommended action: ${cf.recommendation}`
        )
        .join('\n\n')
}

=====================================================
Generated by TexTear 3D Simulation Platform
=====================================================`
    : `=====================================================
BÁO CÁO KỸ THUẬT CẤU HÌNH & AN TOÀN MÁY XÉ VẢI CÔNG NGHIỆP
Thời gian xuất: ${new Date().toLocaleString('vi-VN')}
=====================================================

1. THÔNG SỐ VẬN HÀNH & NGUYÊN LIỆU:
- Loại nguyên liệu: ${materialConfig.materialName}
- Hướng cấp liệu: ${materialConfig.feedDirection === 'left_to_right' ? 'Trái sang Phải' : 'Phải sang Trái'}
- Tốc độ cấp: ${materialConfig.feedSpeedMPerMin} m/phút (Năng suất: ${materialConfig.feedRateKgPerHour} kg/giờ)
- Lực căng danh định: ${materialConfig.nominalTensionN} N
- Hệ thống hút gió: ${suctionConfig.active ? 'ĐANG BẬT' : 'TẮT'} | Tốc độ gió: ${suctionConfig.airVelocity} m/s | Lưu lượng: ${suctionConfig.airflowRate} m3/h

2. DANH MỤC TRỤC & CHI TIẾT MÁY (${components.length} chi tiết):
${components
  .map(
    (c, i) =>
      ` ${i + 1}. ${c.name} [${c.type}]
    - Tọa độ tâm: X=${c.x} mm, Y=${c.y} mm
    - Đường kính Ø: ${c.diameter} mm | Chiều dài: ${c.length} mm
    - Chiều quay: ${c.rotationDir} | Tốc độ: ${c.rpm} RPM
    - Bề mặt: ${c.surfaceType}`
  )
  .join('\n')}

3. BẢNG CỰ LY KHE HỞ THỰC TẾ (CLEARANCE MATRIX):
${clearances
  .map(
    (cl) =>
      `- ${cl.nameA} ↔ ${cl.nameB}: ${cl.gapMm} mm [Chuẩn: ${cl.recommendedGapMin}-${cl.recommendedGapMax}mm] -> ${
        cl.gapMm < 0 ? 'CẢNH BÁO VA CHẠM' : cl.status === 'optimal' ? 'ĐẠT CHUẨN' : 'CẦN CHỈNH'
      }`
  )
  .join('\n')}

4. ĐÁNH GIÁ AN TOÀN & CẢNH BÁO KỸ THUẬT (${conflicts.length} lưu ý):
${
  conflicts.length === 0
    ? ' [✓] HỆ THỐNG AN TOÀN TUYỆT ĐỐI. Không có xung đột chiều quay hay va chạm cơ khí.'
    : conflicts
        .map(
          (cf, i) =>
            ` [!] CẢNH BÁO #${i + 1} (${cf.level.toUpperCase()}): ${cf.title}
     - Chi tiết: ${cf.description}
     - Đề xuất khắc phục: ${cf.recommendation}`
        )
        .join('\n\n')
}

=====================================================
Báo cáo được trích xuất từ phần mềm mô phỏng TexTear 3D
=====================================================`;

  const handleCopy = () => {
    const textToCopy = activeTab === 'json' ? jsonString : technicalReport;
    navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const content = activeTab === 'json' ? jsonString : technicalReport;
    const extension = activeTab === 'json' ? 'json' : 'txt';
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `textile_machine_config_${Date.now()}.${extension}`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/80 backdrop-blur-sm p-4">
      <div className="bg-slate-900 border border-slate-700 w-full max-w-2xl rounded-xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh]">
        {/* Modal Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-900/50">
          <div>
            <h2 className="text-base font-semibold text-slate-100">{t.exportModalTitle}</h2>
            <p className="text-xs text-slate-400">{t.exportModalSubtitle}</p>
          </div>
          <button
            onClick={onClose}
            className="p-1 text-slate-400 hover:text-slate-200 hover:bg-slate-800 rounded transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tab Buttons */}
        <div className="flex items-center gap-2 px-6 pt-3 border-b border-slate-800 bg-slate-950/50">
          <button
            onClick={() => setActiveTab('report')}
            className={`flex items-center gap-2 px-4 py-2 border-b-2 text-xs font-medium transition-colors cursor-pointer ${
              activeTab === 'report'
                ? 'border-sky-500 text-sky-400 bg-slate-900/60 rounded-t'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            <FileText className="w-4 h-4" />
            <span>{t.reportTab}</span>
          </button>
          <button
            onClick={() => setActiveTab('json')}
            className={`flex items-center gap-2 px-4 py-2 border-b-2 text-xs font-medium transition-colors cursor-pointer ${
              activeTab === 'json'
                ? 'border-sky-500 text-sky-400 bg-slate-900/60 rounded-t'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            <span>{t.jsonTab}</span>
          </button>
        </div>

        {/* Modal Content */}
        <div className="flex-1 overflow-y-auto p-6">
          <pre className="p-4 bg-slate-950 rounded-lg border border-slate-800 text-slate-300 font-mono text-xs overflow-x-auto whitespace-pre-wrap leading-relaxed">
            {activeTab === 'json' ? jsonString : technicalReport}
          </pre>
        </div>

        {/* Modal Footer */}
        <div className="flex items-center justify-between px-6 py-4 border-t border-slate-800 bg-slate-900/50">
          <span className="text-xs text-slate-500">
            {components.length} {t.itemsCount} • {conflicts.length === 0 ? (isEn ? 'Safe' : 'Đạt chuẩn an toàn') : (isEn ? 'Warnings present' : 'Có cảnh báo')}
          </span>

          <div className="flex items-center gap-2.5">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium text-slate-300 bg-slate-800 hover:bg-slate-700 rounded-lg transition-colors cursor-pointer"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? t.copiedSuccess : t.copyReportBtn}</span>
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-4 py-1.5 text-xs font-semibold text-white bg-sky-600 hover:bg-sky-500 rounded-lg transition-colors shadow-sm cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>{activeTab === 'json' ? t.downloadJsonBtn : t.downloadReportBtn}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
